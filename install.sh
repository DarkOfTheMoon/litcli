#!/usr/bin/env bash
# 安装 litcli(生产):`pip install --break-system-packages --user .` 把当前源码**复制**到用户
# 站点(非 editable),产出冻结快照;console_script 落到 ~/.local/bin/litcli(已在 PATH)。
# 生产装的是快照,与仓库源码**解耦**:生产期间改源码不波及已装版本(要发布新版本重跑本脚本)。
# 开发请走仓库内 `./bin/litcli`(独立用源码,不影响生产安装)。
# 本机 Python 3.12 是 PEP 668 externally-managed(系统/用户 pip 默认被拦),故必须 --break-system-packages;
# litcli 的依赖(httpx / tenacity / pyrate-limiter / lxml)随程序装进用户站点,不动 apt 管理的系统包;
# --user 限定用户作用域,无需 sudo、不写 /usr/lib。
#
# 可选 --with-cnki / --with-douban:额外安装 Playwright + Chromium(cnki / douban 浏览器驱动后端用,
# 不是核心依赖;二者共用同一 playwright 依赖,只装一次)。
#
# 技能分发(不绑定某个 agent):源是 skills/litcli/SKILL.md。默认**自动探测**已安装的 agent 配置目录
# (~/.claude / ~/.codex / ~/.gemini / ~/.cursor),只往探测到的那些装;同时总在
# ~/.local/share/litcli/skill/SKILL.md 留一份中立副本,其它 agent 可直接引用该路径。
# 用 --skills <claude|codex|gemini|cursor|all> 显式指定(逗号分隔)、--no-skills 跳过、--skills-only 只装技能。
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN_DIR="${HOME}/.local/bin"
SHARE_DIR="${XDG_DATA_HOME:-${HOME}/.local/share}/litcli"
SKILL_DIR="${SHARE_DIR}/skill"
SKILL_SRC="${HERE}/skills/litcli/SKILL.md"
MARK_START="<!-- litcli:skill:start (generated by install.sh; re-running replaces this block) -->"
MARK_END="<!-- litcli:skill:end -->"
WITH_PLAYWRIGHT=0
WITH_CNKI=0
WITH_DOUBAN=0
DO_SKILLS=1
INSTALL_PKG=1
SKILL_TARGETS=""

usage() {
  sed -n '2,22p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --with-cnki) WITH_CNKI=1; WITH_PLAYWRIGHT=1 ;;
    --with-douban) WITH_DOUBAN=1; WITH_PLAYWRIGHT=1 ;;
    --skills)
      if [ "$#" -lt 2 ]; then
        echo "[litcli] 错误: --skills 需要一个值(claude|codex|gemini|cursor|all)" >&2
        exit 1
      fi
      SKILL_TARGETS="$2"; shift
      ;;
    --skills=*) SKILL_TARGETS="${1#--skills=}" ;;
    --no-skills) DO_SKILLS=0 ;;
    --skills-only) INSTALL_PKG=0 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "[litcli] 未知参数: $1(见 ./install.sh --help)" >&2; exit 1 ;;
  esac
  shift
done
cd "${HERE}"

# ---- 技能分发 ----

# 正文(剥掉 YAML frontmatter:只有 SKILL 目录树吃它,其余形态原样并入)
skill_body() {
  awk 'BEGIN { n = 0 }
       n < 2 { if ($0 ~ /^---[[:space:]]*$/) n++; next }
       { print }' "${SKILL_SRC}" | sed '/./,$!d'  # 去掉 frontmatter 留下的前导空行
}

# 目标名 -> 安装动作。每种 agent 的落点和格式都不同,所以逐个写而不是套模板。
install_skill() {
  local target="$1"
  case "${target}" in
    claude)
      if [ -f "${HOME}/.claude/skills/zotero/SKILL.md" ] \
         && [ ! -f "${HOME}/.claude/skills/litcli/SKILL.md" ]; then
        echo "[litcli] 提示: 旧版技能留在 ~/.claude/skills/zotero,可按需删除(本脚本不自动删)"
      fi
      mkdir -p "${HOME}/.claude/skills/litcli"
      cp -f "${SKILL_SRC}" "${HOME}/.claude/skills/litcli/SKILL.md"
      echo "[litcli] 技能 → ~/.claude/skills/litcli/SKILL.md"
      ;;
    codex)
      mkdir -p "${HOME}/.codex/prompts"
      skill_body > "${HOME}/.codex/prompts/litcli.md"
      echo "[litcli] 技能 → ~/.codex/prompts/litcli.md"
      ;;
    cursor)
      mkdir -p "${HOME}/.cursor/rules"
      {
        echo '---'
        echo 'description: 用 litcli 与用户的学术资料互操作(检索/导出引文/读全文/写库)'
        echo 'globs:'
        echo 'alwaysApply: false'
        echo '---'
        skill_body
      } > "${HOME}/.cursor/rules/litcli.mdc"
      echo "[litcli] 技能 → ~/.cursor/rules/litcli.mdc"
      ;;
    gemini)
      local file="${HOME}/.gemini/GEMINI.md"
      mkdir -p "${HOME}/.gemini"
      if [ -f "${file}" ]; then  # 去掉上一次写入的块,保证重跑幂等
        awk -v s="${MARK_START}" -v e="${MARK_END}" \
          '$0 == s { skip = 1 } !skip { print } $0 == e { skip = 0 }' "${file}" > "${file}.tmp"
        mv "${file}.tmp" "${file}"
      fi
      { printf '%s\n' "${MARK_START}"; skill_body; printf '%s\n' "${MARK_END}"; } >> "${file}"
      echo "[litcli] 技能 → ${file}(标记块,重跑会替换)"
      ;;
    *)
      echo "[litcli] 未知技能目标: ${target}(支持 claude|codex|gemini|cursor|all)" >&2
      return 1
      ;;
  esac
}

detect_skill_targets() {
  local found="" dir name
  for dir in "${HOME}/.claude" "${HOME}/.codex" "${HOME}/.gemini" "${HOME}/.cursor"; do
    if [ -d "${dir}" ]; then
      name="${dir##*/}"
      found="${found}${name#.} "
    fi
  done
  printf '%s' "${found}"
}

run_skill_install() {
  if [ ! -f "${SKILL_SRC}" ]; then
    echo "[litcli] 警告: 未找到 ${SKILL_SRC},已跳过技能分发" >&2
    return 0
  fi
  mkdir -p "${SKILL_DIR}"
  cp -f "${SKILL_SRC}" "${SKILL_DIR}/SKILL.md"
  echo "[litcli] 技能 → ${SKILL_DIR}/SKILL.md(中立副本,任何 agent 都可引用此路径)"

  local targets="${SKILL_TARGETS}"
  if [ -z "${targets}" ]; then
    targets="$(detect_skill_targets)"
    if [ -z "${targets}" ]; then
      echo "[litcli] 未探测到 agent 配置目录(~/.claude / ~/.codex / ~/.gemini / ~/.cursor);用 --skills=claude 等显式指定"
      return 0
    fi
  fi
  case " ${targets} " in *" all "*|" all "*) targets="claude codex gemini cursor" ;; esac
  local t
  for t in ${targets//,/ }; do
    install_skill "${t}"
  done
}

# ---- 包安装 ----

if [ "${INSTALL_PKG}" = "1" ]; then
  if ! command -v python3 >/dev/null 2>&1; then
    echo "[litcli] 错误: 未找到 python3,无法安装" >&2
    exit 1
  fi

  # 普通安装(非 editable):把当前源码**复制**进用户站点,产出冻结生产快照。
  # 注意不要用 `-e`(editable 会引用仓库源码,生产期间改源码将即时波及运行中的命令)。
  # 版本号由 pip 输出(Successfully installed litcli-0.1.0)呈现,此处不再多起一个 pip 子进程查。
  python3 -m pip install --break-system-packages --user .
  echo "[litcli] 已安装(快照,复制)"

  if [ "${WITH_PLAYWRIGHT}" = "1" ]; then
    echo "[litcli] 安装浏览器驱动后端依赖(Playwright + Chromium)..."
    python3 -m pip install --break-system-packages --user playwright
    python3 -m playwright install chromium
    if [ "${WITH_CNKI}" = "1" ]; then
      echo "[litcli] CNKI 依赖已装。首次搜索会在可见浏览器里请你手动过滑块 + 登录知网(校外账号),之后会话复用。"
    fi
    if [ "${WITH_DOUBAN}" = "1" ]; then
      echo "[litcli] 豆瓣依赖已装。豆瓣检索默认无头(SSR 直接给书目 JSON),仅被风控时需人工处理。"
    fi
  fi
fi

if [ "${DO_SKILLS}" = "1" ]; then
  run_skill_install
fi

if [ "${INSTALL_PKG}" = "1" ] && ! printf '%s' "${PATH}" | grep -q "${BIN_DIR}"; then
  echo "[litcli] 提示: PATH 尚无 ${BIN_DIR}。建议在 shell 启动文件加:"
  echo "        export PATH=\"${BIN_DIR}:\$PATH\""
fi

echo "[litcli] 完成。自测: litcli backends"
